#!/usr/bin/env python3
"""Build a training dataset for SignLanguage global-orient/translation correction.

This script does not read raw videos and does not run an extra detector. It
pairs original prediction PKLs with oracle-corrected PKLs generated by
`oracle_optimize_signlanguage_global.py`.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from evaluate_signlanguage_geometry import sequence_sort_key
from signlanguage_global_correction import (
    base_feature,
    correction_target,
    discover_sequences,
    frame_number,
    list_prediction_files,
    load_one_person_or_none,
    normalize_sequence_name,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--pred-root", type=Path, default=Path("outputs_fusion_signlanguage_no_stablized"))
    parser.add_argument("--params-subdir", default="fused_params")
    parser.add_argument("--oracle-subdir", default="fused_params_oracle_upper_body_only_frame")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--sequences", nargs="+", default=["all"])
    parser.add_argument("--feature-preset", choices=("minimal", "upper_global", "full"), default="upper_global")
    parser.add_argument("--temporal-radius", type=int, default=1)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--test-ratio", type=float, default=0.15)
    parser.add_argument("--val-sequences", nargs="*", default=None)
    parser.add_argument("--test-sequences", nargs="*", default=None)
    parser.add_argument("--max-label-rot-deg", type=float, default=60.0)
    parser.add_argument("--max-label-transl", type=float, default=2.5)
    return parser.parse_args()


def split_sequences(args: argparse.Namespace, sequences: list[str]) -> dict[str, str]:
    if args.val_sequences is not None or args.test_sequences is not None:
        val = {normalize_sequence_name(x) for x in (args.val_sequences or [])}
        test = {normalize_sequence_name(x) for x in (args.test_sequences or [])}
        overlap = val & test
        if overlap:
            raise ValueError(f"Sequences cannot be both val and test: {sorted(overlap)}")
        return {
            sequence: "test" if sequence in test else "val" if sequence in val else "train"
            for sequence in sequences
        }

    count = len(sequences)
    test_count = int(round(count * args.test_ratio))
    val_count = int(round(count * args.val_ratio))
    if count >= 3:
        test_count = max(1, test_count)
        val_count = max(1, val_count)
    if val_count + test_count >= count:
        test_count = max(0, min(test_count, count - 2))
        val_count = max(0, min(val_count, count - test_count - 1))
    train_end = count - val_count - test_count
    val_end = count - test_count
    return {
        sequence: "train" if index < train_end else "val" if index < val_end else "test"
        for index, sequence in enumerate(sequences)
    }


def temporal_stack(sequence_rows: list[dict], radius: int) -> list[np.ndarray]:
    if radius <= 0:
        return [row["base_feature"] for row in sequence_rows]
    features = [row["base_feature"] for row in sequence_rows]
    output = []
    last_index = len(features) - 1
    for index in range(len(features)):
        stacked = []
        for offset in range(-radius, radius + 1):
            stacked.append(features[min(max(index + offset, 0), last_index)])
        output.append(np.concatenate(stacked, axis=0))
    return output


def main() -> None:
    args = parse_args()
    pred_root = args.pred_root.resolve()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.sequences == ["all"]:
        sequences = discover_sequences(pred_root, args.params_subdir)
    else:
        sequences = sorted([normalize_sequence_name(x) for x in args.sequences], key=sequence_sort_key)
    if not sequences:
        raise ValueError(f"No sequences found under {pred_root}/{args.params_subdir}")

    sequence_splits = split_sequences(args, sequences)
    all_rows: list[dict] = []
    skipped = []
    max_rot = np.deg2rad(args.max_label_rot_deg) if args.max_label_rot_deg > 0 else None

    for sequence in sequences:
        sequence_rows = []
        original_files = list_prediction_files(pred_root, sequence, args.params_subdir)
        oracle_dir = pred_root / sequence / args.oracle_subdir
        for original_path in original_files:
            oracle_path = oracle_dir / original_path.name
            if not oracle_path.exists():
                skipped.append({"sequence": sequence, "file": str(original_path), "reason": "missing_oracle"})
                continue
            original = load_one_person_or_none(original_path)
            oracle = load_one_person_or_none(oracle_path)
            if original is None or oracle is None:
                skipped.append({"sequence": sequence, "file": str(original_path), "reason": "bad_original_or_oracle"})
                continue
            target = correction_target(original, oracle)
            if max_rot is not None and np.linalg.norm(target[:3]) > max_rot:
                skipped.append({"sequence": sequence, "file": str(original_path), "reason": "label_rotation_outlier"})
                continue
            if args.max_label_transl > 0 and np.linalg.norm(target[3:]) > args.max_label_transl:
                skipped.append({"sequence": sequence, "file": str(original_path), "reason": "label_translation_outlier"})
                continue
            sequence_rows.append(
                {
                    "sequence": sequence,
                    "frame": frame_number(original_path),
                    "file": str(original_path),
                    "oracle_file": str(oracle_path),
                    "base_feature": base_feature(original, args.feature_preset),
                    "target": target,
                    "split": sequence_splits[sequence],
                }
            )
        sequence_rows.sort(key=lambda row: row["frame"])
        context_features = temporal_stack(sequence_rows, args.temporal_radius)
        for row, feature in zip(sequence_rows, context_features):
            row["feature"] = feature.astype(np.float32)
            del row["base_feature"]
            all_rows.append(row)

    if not all_rows:
        raise ValueError("No usable original/oracle pairs found")

    x = np.stack([row["feature"] for row in all_rows]).astype(np.float32)
    y = np.stack([row["target"] for row in all_rows]).astype(np.float32)
    sequences_array = np.asarray([row["sequence"] for row in all_rows])
    frames = np.asarray([row["frame"] for row in all_rows], dtype=np.int64)
    files = np.asarray([row["file"] for row in all_rows])
    oracle_files = np.asarray([row["oracle_file"] for row in all_rows])
    split_names = np.asarray([row["split"] for row in all_rows])
    split_ids = np.asarray(
        [{"train": 0, "val": 1, "test": 2}[row["split"]] for row in all_rows],
        dtype=np.int64,
    )
    np.savez_compressed(
        args.output,
        x=x,
        y=y,
        sequence=sequences_array,
        frame=frames,
        path=files,
        oracle_file=oracle_files,
        split=split_ids,
        split_name=split_names,
        feature_preset=np.asarray(args.feature_preset),
        temporal_radius=np.asarray(args.temporal_radius, dtype=np.int64),
    )

    counts = {
        split: int(np.sum(split_names == split))
        for split in ("train", "val", "test")
    }
    sequence_counts = {
        split: sorted([seq for seq, seq_split in sequence_splits.items() if seq_split == split], key=sequence_sort_key)
        for split in ("train", "val", "test")
    }
    report = {
        "output": str(args.output.resolve()),
        "pred_root": str(pred_root),
        "params_subdir": args.params_subdir,
        "oracle_subdir": args.oracle_subdir,
        "feature_preset": args.feature_preset,
        "temporal_radius": args.temporal_radius,
        "feature_dim": int(x.shape[1]),
        "target_dim": int(y.shape[1]),
        "frames": int(len(all_rows)),
        "split_counts": counts,
        "sequence_splits": sequence_counts,
        "skipped_count": len(skipped),
        "skipped_sample": skipped[:20],
    }
    report_path = args.output.with_suffix(".json")
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
